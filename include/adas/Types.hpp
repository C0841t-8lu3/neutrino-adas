#pragma once

#include <string>
#include <vector>

namespace adas {

// Scoped Drive Modes (preserving exact wire values 0..6)
enum class DriveMode : int {
    MANUAL = 0,
    CRUISING = 1,
    ACC_FOLLOWING = 2,
    LANE_CHANGING = 3,
    TURNING_INTERSECTION = 4,
    AEB_EMERGENCY = 5,
    STOPPED = 6
};

// Tesla-Style FSD Driving Profiles
enum class DriveProfile : int {
    CHILL = 0,
    STANDARD = 1,
    HURRY = 2
};

// Mode to string conversion
const char* modeToString(DriveMode mode);
const char* modeToString(int mode);

// Profile to string conversion
const char* profileToString(DriveProfile profile);
const char* profileToString(int profile);

// Vehicle Kinematic State
struct VehicleState {
    float x = 0.0f;              // Lateral position (meters, lane 1 = 0.0)
    float y = 0.0f;              // Elevation (meters)
    float z = 0.0f;              // Longitudinal distance (meters)
    float speed = 0.0f;          // m/s forward velocity
    float heading = 0.0f;        // radians (yaw)
    float steer_angle = 0.0f;    // radians front wheel angle
    int current_lane = 1;        // 0: Left, 1: Center, 2: Right
    int target_lane = 1;
    uint64_t seq = 0;            // Monotonic telemetry frame sequence counter

    // Optional Point-to-Point Navigation Route Fields
    bool has_route = false;
    float ref_x = 0.0f;
    float ref_z = 0.0f;
    float ref_heading = 0.0f;
    float path_curvature = 0.0f;
    float next_curvature = 0.0f; // Lookahead curvature for predictive cornering
    float dist_to_goal = 99999.0f;
    int turn_signal_hint = 0;    // -1: Left, 0: None, +1: Right
    float dist_to_next_turn = 999.0f; // Distance in meters to upcoming turn
    int pre_turn_lane_hint = 0;       // -1: Left turn upcoming, +1: Right turn upcoming, 0: None
    bool in_intersection = false;     // True if ego vehicle is inside an intersection box

    // Optional FSD Driving Profile (defaults to STANDARD)
    DriveProfile drive_profile = DriveProfile::STANDARD;
};

// Traffic Obstacle detected by sensors
struct Obstacle {
    float x = 0.0f;
    float z = 0.0f;
    float speed = 0.0f;
    float vx = 0.0f;
    float vz = 0.0f;
    float heading = 0.0f;
    float width = 2.0f;
    float length = 4.5f;
    int id = 0;
    int type = 0;                // 0: Car, 1: Truck, 2: Pedestrian, 3: Stop Line
};

// Sensor scan results
struct ForwardScanResult {
    float lead_distance = 999.0f;
    float lead_rel_speed = 0.0f;
    float lead_lat = 0.0f;
    float time_to_collision = 999.0f;
    bool pedestrian_ahead = false;
    bool is_lead_stop_line = false;
    int lead_type = 0;
};

struct BlindSpotResult {
    bool left_bsm = false;
    bool right_bsm = false;
};

// Tunable ADAS Configuration Parameters
struct AdasConfig {
    float target_speed_mps = 14.0f;      // 50 km/h (~31 mph)
    float wheelbase_m = 2.75f;           // Vehicle wheelbase L for Ackermann feedforward
    float min_safe_dist = 7.5f;          // IDM standstill spacing s0 (meters)
    float time_headway = 1.6f;           // IDM time headway T (CHILL: 2.0s, STANDARD: 1.6s, HURRY: 1.25s)
    float max_accel = 2.5f;              // m/s^2 (CHILL: 1.8, STANDARD: 2.5, HURRY: 3.2)
    float idm_b_comfort = 2.0f;          // IDM comfortable deceleration (m/s^2)
    float max_service_brake = 3.8f;      // m/s^2 (CHILL: 3.0, STANDARD: 3.8, HURRY: 4.5)
    float emergency_brake_accel = 8.5f;  // m/s^2
    float max_jerk = 2.8f;               // m/s^3 (CHILL: 2.2, STANDARD: 2.8, HURRY: 3.5)
    float max_steer_rate = 1.8f;         // rad/s steering rate limit
    float stanley_k_psi = 1.25f;
    float stanley_k_e = 1.95f;
    float stanley_k_d = 0.25f;           // Lateral error rate damping gain
    float stanley_steer_clamp = 0.65f;
    DriveProfile profile = DriveProfile::STANDARD;

    void applyProfile(DriveProfile p) {
        profile = p;
        switch (p) {
            case DriveProfile::CHILL:
                min_safe_dist = 8.5f;
                time_headway = 2.0f;
                max_accel = 1.8f;
                idm_b_comfort = 1.8f;
                max_service_brake = 3.0f;
                max_jerk = 2.2f;
                break;
            case DriveProfile::HURRY:
                min_safe_dist = 6.5f;
                time_headway = 1.25f;
                max_accel = 3.2f;
                idm_b_comfort = 2.3f;
                max_service_brake = 4.5f;
                max_jerk = 3.5f;
                break;
            case DriveProfile::STANDARD:
            default:
                min_safe_dist = 7.5f;
                time_headway = 1.6f;
                max_accel = 2.5f;
                idm_b_comfort = 2.0f;
                max_service_brake = 3.8f;
                max_jerk = 2.8f;
                break;
        }
    }
};

// Actuator Commands generated by QNX RTOS Core
struct AdasOutput {
    float throttle = 0.0f;       // 0.0 to 1.0
    float brake = 0.0f;          // 0.0 to 1.0
    float steer_cmd = 0.0f;      // -1.0 to +1.0
    bool left_turn_signal = false;
    bool right_turn_signal = false;
    bool hazard_lights = false;
    bool horn_active = false;
    bool brake_lights = false;
    bool left_mirror_blind_spot = false;
    bool right_mirror_blind_spot = false;
    DriveMode drive_mode = DriveMode::CRUISING;
    DriveProfile drive_profile = DriveProfile::STANDARD;
    float lateral_nudge = 0.0f;
    float lead_distance = 999.0f;
    float lead_rel_speed = 0.0f;
    float time_to_collision = 999.0f;
    uint64_t ack_seq = 0;
    bool watchdog_ok = true;
    std::string status_message;
};

} // namespace adas
