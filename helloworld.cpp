enum DriveMode {
    MODE_MANUAL = 0,
    MODE_CRUISING = 1,
    MODE_ACC_FOLLOWING = 2,
    MODE_LANE_CHANGING = 3,
    MODE_TURNING_INTERSECTION = 4,
    MODE_AEB_EMERGENCY = 5,
    MODE_STOPPED = 6
};

const char* modeToString(int mode) {
    switch (mode) {
        case MODE_CRUISING:              return "CRUISING";
        case MODE_ACC_FOLLOWING:         return "ACC FOLLOWING";
        case MODE_LANE_CHANGING:         return "LANE CHANGING";
        case MODE_TURNING_INTERSECTION:  return "INTERSECTION TURN";
        case MODE_AEB_EMERGENCY:         return "AEB EMERGENCY BRAKE";
        case MODE_STOPPED:               return "STOPPED";
        default:                         return "MANUAL";
    }
}

// Vehicle Kinematic State
struct VehicleState {
    float x = 0.0f;              // Lateral position (meters, lane 1 = 0.0)
    float y = 0.0f;              // Elevation (meters)
    float z = 0.0f;              // Longitudinal distance (meters)
    float speed = 0.0f;          // m/s forward velocity
    float heading = 0.0f;        // radians (yaw)
    float steer_angle = 0.0f;    // radians front wheel angle
    int current_lane = 1;        // 0: Left, 1: Center, 2: Right
    int target_lane = 1;
};

// Traffic Obstacle detected by sensors
struct Obstacle {
    float x = 0.0f;
    float z = 0.0f;
    float speed = 0.0f;
    float heading = 0.0f;
    float width = 2.0f;
    float length = 4.5f;
    int id = 0;
    int type = 0;                // 0: Car, 1: Truck, 2: Pedestrian
};

// Actuator Commands generated by QNX RTOS Core
struct AdasOutput {
    float throttle = 0.0f;       // 0.0 to 1.0
    float brake = 0.0f;          // 0.0 to 1.0
    float steer_cmd = 0.0f;      // -1.0 to +1.0
    bool left_turn_signal = false;
    bool right_turn_signal = false;
    bool hazard_lights = false;
    bool horn_active = false;
    bool brake_lights = false;
    bool left_mirror_blind_spot = false;
    bool right_mirror_blind_spot = false;
    int drive_mode = MODE_CRUISING;
    float lead_distance = 999.0f;
    float lead_rel_speed = 0.0f;
    float time_to_collision = 999.0f;
    std::string status_message;
};

// QNX ADAS L3 Autonomous Controller
class QnxAdasController {
public:
    float target_speed_mps = 14.0f;      // 50 km/h (~31 mph)
    float min_safe_dist = 6.5f;          // meters
    float time_headway = 1.4f;           // seconds
    float max_accel = 2.5f;              // m/s^2
    float max_service_brake = 3.5f;      // m/s^2
    float emergency_brake_accel = 8.5f;  // m/s^2

    int current_mode = MODE_CRUISING;
    float blinker_timer = 0.0f;
    bool blinker_phase = false;
    float horn_timer = 0.0f;
    int desired_lane = 1;
    bool lane_change_active = false;
    float lane_change_timer = 0.0f;

    QnxAdasController() {
        current_mode = MODE_CRUISING;
        desired_lane = 1;
    }

    // 1. Forward LiDAR/Radar Scan
    void scanForwardRadar(
        const VehicleState& ego,
        const std::vector<Obstacle>& obstacles,
        float& out_lead_dist,
        float& out_lead_rel_speed,
        float& out_ttc,
        bool& out_pedestrian_ahead
    ) {
        out_lead_dist = 999.0f;
        out_lead_rel_speed = 0.0f;
        out_ttc = 999.0f;
        out_pedestrian_ahead = false;

        float sinH = std::sin(ego.heading);
        float cosH = std::cos(ego.heading);

        for (const auto& obs : obstacles) {
            float dx = obs.x - ego.x;
            float dz = obs.z - ego.z;

            // Project into ego vehicle coordinate frame
            float fwd = dx * sinH + dz * cosH;
            float lat = dx * cosH - dz * sinH;

            // Forward detection corridor
            if (fwd > 0.8f && fwd < 85.0f && std::abs(lat) < 2.3f) {
                float dist = fwd - (obs.length * 0.5f) - 2.2f;
                if (dist < out_lead_dist) {
                    out_lead_dist = std::max(0.1f, dist);
                    out_lead_rel_speed = obs.speed - ego.speed;
                    if (obs.type == 2) {
                        out_pedestrian_ahead = true;
                    }
                }
            }
        }

        if (out_lead_rel_speed < -0.1f && out_lead_dist < 85.0f) {
            out_ttc = out_lead_dist / (-out_lead_rel_speed);
        }
    }

    // 2. Dual Side-Mirror Blind-Spot Radar Scan
    void scanBlindSpots(
        const VehicleState& ego,
        const std::vector<Obstacle>& obstacles,
        bool& out_left_bsm,
        bool& out_right_bsm
    ) {
        out_left_bsm = false;
        out_right_bsm = false;

        float sinH = std::sin(ego.heading);
        float cosH = std::cos(ego.heading);

        for (const auto& obs : obstacles) {
            float dx = obs.x - ego.x;
            float dz = obs.z - ego.z;

            float fwd = dx * sinH + dz * cosH;
            float lat = dx * cosH - dz * sinH;

            // Blind-spot zone: -8.5m behind up to +3.0m beside
            if (fwd >= -8.5f && fwd <= 3.0f) {
                // Left mirror blind spot zone (-4.8m to -1.3m)
                if (lat <= -1.3f && lat >= -4.8f) {
                    out_left_bsm = true;
                }
                // Right mirror blind spot zone (+1.3m to +4.8m)
                if (lat >= 1.3f && lat <= 4.8f) {
                    out_right_bsm = true;
                }
            }
        }
    }

    // Core Real-Time Decision Loop
    AdasOutput step(const VehicleState& ego, const std::vector<Obstacle>& obstacles, float dt) {
        AdasOutput out;

        // Blinker flash clock (3 Hz)
        blinker_timer += dt;
        if (blinker_timer >= 0.33f) {
            blinker_timer = 0.0f;
            blinker_phase = !blinker_phase;
        }

        // Horn timer
        if (horn_timer > 0.0f) {
            horn_timer -= dt;
        }

        // Perception
        float lead_dist = 999.0f;
        float lead_rel_speed = 0.0f;
        float ttc = 999.0f;
        bool pedestrian_ahead = false;
        scanForwardRadar(ego, obstacles, lead_dist, lead_rel_speed, ttc, pedestrian_ahead);

        bool left_bsm = false;
        bool right_bsm = false;
        scanBlindSpots(ego, obstacles, left_bsm, right_bsm);

        out.left_mirror_blind_spot = left_bsm;
        out.right_mirror_blind_spot = right_bsm;
        out.lead_distance = lead_dist;
        out.lead_rel_speed = lead_rel_speed;
        out.time_to_collision = ttc;

        float throttle = 0.0f;
        float brake = 0.0f;
        bool hazard = false;
        bool horn = false;

        // Overtake & Side-Mirror Accident Prevention
        if (ego.target_lane != ego.current_lane) {
            if (ego.target_lane < ego.current_lane) {
                // Requested left lane change
                if (left_bsm) {
                    // ACCIDENT PREVENTION: Left mirror blind spot occupied!
                    desired_lane = ego.current_lane;
                    lane_change_active = false;
                    hazard = true;
                    horn = true;
                    horn_timer = 0.4f;
                    out.status_message = "QNX BSM: ACCIDENT PREVENTED! Left Blind Spot Occupied - Lane Change Aborted";
                } else {
                    desired_lane = ego.target_lane;
                    lane_change_active = true;
                    lane_change_timer = 3.2f;
                }
            } else if (ego.target_lane > ego.current_lane) {
                // Requested right lane change
                if (right_bsm) {
                    // ACCIDENT PREVENTION: Right mirror blind spot occupied!
                    desired_lane = ego.current_lane;
                    lane_change_active = false;
                    hazard = true;
                    horn = true;
                    horn_timer = 0.4f;
                    out.status_message = "QNX BSM: ACCIDENT PREVENTED! Right Blind Spot Occupied - Lane Change Aborted";
                } else {
                    desired_lane = ego.target_lane;
                    lane_change_active = true;
                    lane_change_timer = 3.2f;
                }
            }
        } else if (!lane_change_active && lead_dist < 28.0f && (ego.speed + lead_rel_speed) < 8.5f) {
            if (desired_lane > 0) {
                if (!left_bsm) {
                    // Safe to pass: change to left lane
                    desired_lane = desired_lane - 1;
                    lane_change_active = true;
                    lane_change_timer = 3.5f;
                } else {
                    // ACCIDENT PREVENTION: Left side mirror detects vehicle in blind spot!
                    // QNX safety kernel aborts lane change and maintains safe following!
                    desired_lane = ego.current_lane;
                    hazard = true;
                    out.status_message = "QNX BSM: Left Lane Blocked! Aborting Lane Change (Accident Prevented)";
                }
            }
        }

        if (lane_change_active) {
            lane_change_timer -= dt;
            if (lane_change_timer <= 0.0f) {
                lane_change_active = false;
            }
        }

        // Automatic Emergency Braking (AEB)
        if ((ttc < 1.7f && lead_dist < 32.0f) || (lead_dist < 6.5f && ego.speed > 1.0f) || (pedestrian_ahead && lead_dist < 18.0f)) {
            current_mode = MODE_AEB_EMERGENCY;
            throttle = 0.0f;
            brake = 1.0f; // 100% emergency brake pressure
            hazard = true;
            horn = true;
            horn_timer = 0.5f;

            if (pedestrian_ahead) {
                out.status_message = "QNX AEB: Pedestrian in path! Emergency Braking & Horn Triggered";
            } else {
                out.status_message = "QNX AEB: Collision hazard! Full Emergency Deceleration (-8.5 m/s2)";
            }
        }
        // Adaptive Cruise Control (ACC) & Intersection Stop-Line Deceleration
        else if (lead_dist < 85.0f) {
            current_mode = MODE_ACC_FOLLOWING;
            float desired_gap = min_safe_dist + (ego.speed * time_headway);

            // If lead obstacle is stationary (e.g. red light stop line), apply kinematic stopping curve
            bool lead_is_stationary = (std::abs(lead_rel_speed + ego.speed) < 0.5f);
            float target_accel = 0.0f;

            if (lead_is_stationary && ego.speed > 0.5f) {
                float remaining_stopping_dist = std::max(0.5f, lead_dist - min_safe_dist);
                float req_decel = (ego.speed * ego.speed) / (2.0f * remaining_stopping_dist);
                target_accel = -std::min(max_service_brake, std::max(0.8f, req_decel));
            } else {
                float gap_error = lead_dist - desired_gap;
                target_accel = (0.55f * gap_error) + (0.85f * lead_rel_speed);
            }

            if (target_accel >= 0.0f) {
                throttle = std::min(1.0f, target_accel / max_accel);
                brake = 0.0f;
            } else {
                throttle = 0.0f;
                brake = std::min(1.0f, -target_accel / max_service_brake);
            }

            if (ego.speed < 0.6f && lead_is_stationary && lead_dist <= 15.0f) {
                current_mode = MODE_STOPPED;
                throttle = 0.0f;
                brake = 0.8f;
                out.status_message = "QNX Safety Stop: Holding at Red Light / Stop Line";
            } else if (out.status_message.empty()) {
                std::ostringstream ss;
                ss << "QNX ACC: Following Lead (" << std::fixed << std::setprecision(1) << lead_dist
                   << "m) | Speed: " << (ego.speed * 3.6f) << " km/h";
                out.status_message = ss.str();
            }
        }
        // Free Cruising
        else {
            current_mode = MODE_CRUISING;
            float speed_error = target_speed_mps - ego.speed;
            if (speed_error >= 0.0f) {
                throttle = std::min(1.0f, speed_error * 0.45f);
                brake = 0.0f;
            } else {
                throttle = 0.0f;
                brake = std::min(0.6f, -speed_error * 0.30f);
            }

            if (out.status_message.empty()) {
                out.status_message = "QNX Cruising 50 km/h | Lane Centering Active | Watchdog OK";
            }
        }

        if (ego.speed < 0.15f && brake > 0.0f && current_mode == MODE_AEB_EMERGENCY) {
            current_mode = MODE_STOPPED;
            out.status_message = "QNX Safety Stop: Vehicle Stopped Before Obstacle";
        }

        // Lateral Steering Control using Stanley Lateral Tracking Controller
        float target_x = 3.6f;
        if (desired_lane == 0) {
            target_x = 0.1f;
        } else if (desired_lane == 2) {
            target_x = 7.1f;
        }
        float lateral_error = ego.x - target_x;

        // Normalize heading error to [-pi, pi] (road heading along 5th Ave Southbound is 0.0)
        float heading_error = ego.heading;
        while (heading_error > 3.14159265f) heading_error -= 6.2831853f;
        while (heading_error < -3.14159265f) heading_error += 6.2831853f;

        // Stanley controller formulation with velocity scheduling:
        // delta = -(k_psi * heading_error) - atan2(k_e * lateral_error, max(2.5, speed))
        float k_psi = 1.20f;
        float k_e = 0.75f;
        float steer_cmd = -(k_psi * heading_error) - std::atan2(k_e * lateral_error, std::max(2.5f, ego.speed));
        steer_cmd = std::max(-0.65f, std::min(0.65f, steer_cmd));

        // Turn Signals
        bool left_blinker = false;
        bool right_blinker = false;

        if (hazard) {
            left_blinker = blinker_phase;
            right_blinker = blinker_phase;
        } else if (lane_change_active || lateral_error > 0.4f) {
            left_blinker = blinker_phase;
        } else if (lateral_error < -0.4f) {
            right_blinker = blinker_phase;
        }

        out.throttle = throttle;
        out.brake = brake;
        out.steer_cmd = steer_cmd;
        out.left_turn_signal = left_blinker;
        out.right_turn_signal = right_blinker;
        out.hazard_lights = hazard;
        out.horn_active = horn || (horn_timer > 0.0f);
        out.brake_lights = (brake > 0.15f);
        out.drive_mode = current_mode;

        return out;
    }
};

// Simple JSON helper parser/generator for lightweight network IPC
std::string generateResponseJson(const AdasOutput& out) {
    std::ostringstream ss;
    ss << "{"
       << "\"throttle\":" << out.throttle << ","
       << "\"brake\":" << out.brake << ","
       << "\"steer_cmd\":" << out.steer_cmd << ","
       << "\"left_turn_signal\":" << (out.left_turn_signal ? "true" : "false") << ","
       << "\"right_turn_signal\":" << (out.right_turn_signal ? "true" : "false") << ","
       << "\"hazard_lights\":" << (out.hazard_lights ? "true" : "false") << ","
       << "\"horn_active\":" << (out.horn_active ? "true" : "false") << ","
       << "\"brake_lights\":" << (out.brake_lights ? "true" : "false") << ","
       << "\"left_mirror_blind_spot\":" << (out.left_mirror_blind_spot ? "true" : "false") << ","
       << "\"right_mirror_blind_spot\":" << (out.right_mirror_blind_spot ? "true" : "false") << ","
       << "\"drive_mode\":" << out.drive_mode << ","
       << "\"lead_distance\":" << out.lead_distance << ","
       << "\"lead_rel_speed\":" << out.lead_rel_speed << ","
       << "\"time_to_collision\":" << out.time_to_collision << ","
       << "\"status_message\":\"" << out.status_message << "\""
       << "}\n";
    return ss.str();
}

// Parse incoming telemetry JSON from 3D vehicle
bool parseTelemetryJson(const std::string& str, VehicleState& ego, std::vector<Obstacle>& obstacles, float& dt) {
    dt = 0.016f; // default 60 Hz frame
    obstacles.clear();

    auto parseNumber = [](const std::string& src, const std::string& key) -> float {
        size_t pos = src.find("\"" + key + "\"");
        if (pos == std::string::npos) return 0.0f;
        pos += key.length() + 2;
        while (pos < src.length() && (src[pos] == ' ' || src[pos] == ':')) pos++;
        if (pos >= src.length()) return 0.0f;
        return std::atof(src.c_str() + pos);
    };

    ego.x = parseNumber(str, "x");
    ego.y = parseNumber(str, "y");
    ego.z = parseNumber(str, "z");
    ego.speed = parseNumber(str, "speed");
    ego.heading = parseNumber(str, "heading");
    ego.steer_angle = parseNumber(str, "steer_angle");
    ego.current_lane = static_cast<int>(parseNumber(str, "current_lane"));
    ego.target_lane = static_cast<int>(parseNumber(str, "target_lane"));
    float parsed_dt = parseNumber(str, "dt");
    if (parsed_dt > 0.001f && parsed_dt < 0.1f) dt = parsed_dt;

    // Parse simple obstacle array: "obs":[{"x":...,"z":...,"speed":...,"type":...}]
    size_t obs_pos = str.find("\"obs\"");
    if (obs_pos != std::string::npos) {
        size_t open_bracket = str.find("[", obs_pos);
        size_t end_bracket = str.find("]", obs_pos);
        if (open_bracket != std::string::npos && end_bracket != std::string::npos && end_bracket > open_bracket) {
            std::string obs_substr = str.substr(open_bracket + 1, end_bracket - open_bracket - 1);
            size_t cur = 0;
            while ((cur = obs_substr.find("{", cur)) != std::string::npos) {
                size_t obj_end = obs_substr.find("}", cur);
                if (obj_end == std::string::npos) break;
                std::string item = obs_substr.substr(cur, obj_end - cur + 1);
                Obstacle o;
                o.x = parseNumber(item, "x");
                o.z = parseNumber(item, "z");
                o.speed = parseNumber(item, "speed");
                o.type = static_cast<int>(parseNumber(item, "type"));
                o.length = (o.type == 1) ? 7.0f : 4.5f;
                o.width = (o.type == 1) ? 2.4f : 2.0f;
                obstacles.push_back(o);
                cur = obj_end + 1;
            }
        }
    }

    return true;
}

// QNX Real-time Network Server Mode
void runQnxServer(int port) {
    std::cout << "[QNX RTOS] Initializing High-Speed Real-Time Socket Server on Port " << port << "...\n";

    int server_fd = socket(AF_INET, SOCK_STREAM, 0);
    if (server_fd < 0) {
        perror("socket failed");
        return;
    }

    int opt = 1;
    setsockopt(server_fd, SOL_SOCKET, SO_REUSEADDR, &opt, sizeof(opt));

    sockaddr_in address;
    std::memset(&address, 0, sizeof(address));
    address.sin_family = AF_INET;
    address.sin_addr.s_addr = INADDR_ANY;
    address.sin_port = htons(port);

    if (bind(server_fd, (struct sockaddr*)&address, sizeof(address)) < 0) {
        perror("bind failed");
        close(server_fd);
        return;
    }

    if (listen(server_fd, 3) < 0) {
        perror("listen failed");
        close(server_fd);
        return;
    }

    std::cout << "[QNX RTOS] ADAS L3 Safety Kernel Listening for 3D Vehicle Link...\n";

    QnxAdasController controller;

    while (true) {
        sockaddr_in client_addr;
        socklen_t addrlen = sizeof(client_addr);
        std::cout << "[QNX RTOS] Waiting for 3D Car Connection...\n";
        int client_sock = accept(server_fd, (struct sockaddr*)&client_addr, &addrlen);
        if (client_sock < 0) {
            perror("accept failed");
            continue;
        }

        char client_ip[INET_ADDRSTRLEN];
        inet_ntop(AF_INET, &client_addr.sin_addr, client_ip, INET_ADDRSTRLEN);
        std::cout << "[QNX RTOS] 3D Car Connected from: " << client_ip << "!\n";

        char buffer[4096];
        std::string line_buffer;

        while (true) {
            ssize_t bytes_read = recv(client_sock, buffer, sizeof(buffer) - 1, 0);
            if (bytes_read <= 0) {
                std::cout << "[QNX RTOS] 3D Car Disconnected.\n";
                break;
            }

            buffer[bytes_read] = '\0';
            line_buffer.append(buffer);

            size_t newline_pos = 0;
            while ((newline_pos = line_buffer.find('\n')) != std::string::npos) {
                std::string packet = line_buffer.substr(0, newline_pos);
                line_buffer.erase(0, newline_pos + 1);

                VehicleState ego;
                std::vector<Obstacle> obstacles;
                float dt = 0.016f;

                if (parseTelemetryJson(packet, ego, obstacles, dt)) {
                    AdasOutput out = controller.step(ego, obstacles, dt);
                    std::string resp = generateResponseJson(out);
                    send(client_sock, resp.c_str(), resp.length(), 0);
                }
            }
        }

        close(client_sock);
    }

    close(server_fd);
}

// Standalone QNX Console Simulation (Terminal Test)
void runConsoleSelfTest(int steps) {
    std::cout << "\033[1;36m=== QNX 8.0 NEUTRINO RTOS ADAS L3 SAFETY KERNEL ===\033[0m\n";
    std::cout << "Target: QNX Neutrino 8.0 (x86_64) | Safety Priority: Real-Time\n\n";

    QnxAdasController controller;
    VehicleState ego;
    ego.speed = 10.0f;

    std::vector<Obstacle> obstacles = {
        // Slow truck ahead
        {0.0f, 65.0f, 6.5f, 0.0f, 2.4f, 7.2f, 1, 1},
        // Fast sedan in right lane
        {4.0f, 25.0f, 16.0f, 0.0f, 1.9f, 4.5f, 2, 0},
        // Blind-spot vehicle on Left side (Accident Prevention Test!)
        {-3.8f, -3.0f, 10.5f, 0.0f, 1.9f, 4.4f, 3, 0}
    };

    float dt = 0.1f;
    for (int i = 0; i < steps; ++i) {
        // Move obstacles
        for (auto& o : obstacles) {
            o.z += o.speed * dt;
        }

        // Trigger cut-in hazard at step 80
        if (i == 80) {
            obstacles[0].z = ego.z + 18.0f;
            obstacles[0].speed = 2.0f;
        }

        AdasOutput out = controller.step(ego, obstacles, dt);

        // Update ego kinematics
        float accel = (out.throttle * 2.5f) - (out.brake * 8.5f);
        ego.speed = std::max(0.0f, ego.speed + accel * dt);
        ego.z += ego.speed * dt;
        ego.x += ego.speed * std::sin(ego.heading) * dt;

        if (i % 10 == 0 || out.drive_mode == MODE_AEB_EMERGENCY || out.left_mirror_blind_spot) {
            std::cout << "[Step " << std::setw(3) << i << "] "
                      << "Mode: " << std::setw(20) << modeToString(out.drive_mode)
                      << " | Spd: " << std::setw(5) << std::fixed << std::setprecision(1) << (ego.speed * 3.6f) << " km/h"
                      << " | Lead: " << std::setw(5) << out.lead_distance << "m"
                      << " | Left BSM: " << (out.left_mirror_blind_spot ? "\033[1;31mALERT\033[0m" : "\033[1;32mCLEAR\033[0m")
                      << " | Horn: " << (out.horn_active ? "\033[1;31mON\033[0m" : "OFF")
                      << "\n       MSG: " << out.status_message << "\n";
        }

        usleep(40000);
    }

    std::cout << "\n\033[1;32m[QNX SUCCESS]\033[0m Safety Supervisor Verification Complete.\n";
}

int main(int argc, char* argv[]) {
    int port = 9090;
    bool server_mode = false;

    for (int i = 1; i < argc; ++i) {
        if (std::string(argv[i]) == "--server" || std::string(argv[i]) == "-s") {
            server_mode = true;
        } else if (std::string(argv[i]) == "--port" && i + 1 < argc) {
            port = std::atoi(argv[++i]);
            server_mode = true;
        }
    }

    if (server_mode) {
        runQnxServer(port);
    } else {
        runConsoleSelfTest(120);
    }

    return 0;
}
